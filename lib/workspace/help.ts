function matches(pattern: string, path: string): boolean {
  const a = pattern.split("/")
  const b = path.replace(/\/+$/, "").split("/")
  return a.length === b.length && a.every((seg, i) => seg === "[id]" || seg === b[i])
}

export function helpFor(path: string, audience: HelpAudience): HelpTopic | null {
  return HELP_TOPICS.find((t) => t.audience === audience && t.paths.some((p) => matches(p, path))) ?? null
}
